/** Busca la ficha por nombre (español o inglés). Prefiere el alias más largo que coincida. */
export function findLib(name: string): LibEntry | null {
  const n = nameKey(name);
  if (!n) return null;
  let best: LibEntry | null = null;
  let bestLen = 0;
  for (const e of LIBRARY) {
    for (const a of e.aliases) {
      const hit = n === a || (a.length > 3 && ` ${n} `.includes(` ${a} `));
      if (hit && a.length > bestLen) {
        best = e;
        bestLen = a.length;
      }
    }
  }
  return best;
}

export const libByKey = (k?: string) => LIBRARY.find((e) => e.key === k) ?? null;

/** Nombre en el otro idioma para mostrarlo como referencia. */
export function altName(ex: { name: string; libKey?: string }): { label: string; name: string } | null {
  const lib = libByKey(ex.libKey);
  if (!lib) return null;
  const n = nameKey(ex.name);
  if (n === nameKey(lib.en)) return { label: 'En español', name: lib.name };
  if (n === nameKey(lib.name)) return { label: 'En inglés', name: lib.en };
  return { label: 'Ficha', name: `${lib.name} · ${lib.en}` };
}

/** Nombre en español si difiere del mostrado (referencia bajo el nombre en inglés). */
export function spanishName(ex: { name: string; libKey?: string }) {
  const lib = libByKey(ex.libKey);
  return lib && nameKey(lib.name) !== nameKey(ex.name) ? lib.name : null;
}
