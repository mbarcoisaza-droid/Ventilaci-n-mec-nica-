/**
 * Biblioteca de ejercicios: una ficha por ejercicio con su gráfico y su descripción en español.
 * Las descripciones provienen de las instrucciones entregadas por la persona usuaria (no de internet).
 * Los nombres en inglés y en español son alias de la misma ficha.
 * Las fichas con `pending` no describen una técnica: requieren que el entrenador confirme el movimiento.
 * No hay videos: los enlaces se añaden manualmente (no se inventan identificadores).
 */

export interface LibVariant {
  name: string;
  note?: string;
}

/** Contenido visual y descriptivo de una ficha (también usado para las ediciones del entrenador). */
export interface LibContent {
  summary: string;
  /** Posición inicial. */
  start: string;
  /** Ejecución en pasos breves. */
  steps: string[];
  breathing: string;
  keyPoints: string[];
  errors: string[];
  equipment: string[];
  pose: string;
  easier?: LibVariant;
  harder?: LibVariant;
  lowImpact?: LibVariant;
}

export interface LibEntry extends LibContent {
  key: string;
  /** Nombre en español. */
  name: string;
  /** Nombre en inglés. */
  en: string;
  /** Fragmentos normalizados (minúsculas, sin tildes, guiones como espacios) que identifican el ejercicio. */
  aliases: string[];
  /** Motivo por el que el movimiento debe confirmarlo el entrenador (no se muestra una técnica). */
  pending?: string;
  /** Variante propuesta en las instrucciones, que el entrenador puede aceptar con un toque. */
  candidate?: Partial<LibContent> & { label: string };
}

export const norm = (s: string) =>
  s
    .toLowerCase()
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/[“”"«»'’]/g, '')
    .replace(/\s+/g, ' ')
    .trim();

/** Normalización para buscar: además trata los guiones como espacios. */
export const nameKey = (s: string) => norm(s).replace(/-/g, ' ').replace(/\s+/g, ' ');

/** Versión del contenido de la biblioteca; al subirla se actualizan los ejercicios guardados. */
export const LIB_VERSION = 2;
export const PENDING_POSE = 'pendiente';
export const PENDING_LABEL = 'Descripción por confirmar';

const SIN_SALTO = 'Alternativa sin salto';

type Def = Omit<LibEntry, 'aliases' | 'breathing' | 'keyPoints' | 'errors' | 'equipment' | 'summary'> &
  Partial<Pick<LibEntry, 'breathing' | 'keyPoints' | 'errors' | 'equipment' | 'summary'>> & { aliases?: string[] };

function ex(d: Def): LibEntry {
  return {
    breathing: '',
    keyPoints: [],
    errors: [],
    equipment: [],
    summary: '',
    ...d,
    aliases: [d.name, d.en, ...(d.aliases ?? [])].map(nameKey),
  };
}

/** Ficha pendiente: dibujo neutral y etiqueta «Descripción por confirmar». */
function pend(d: { key: string; name: string; en: string; aliases?: string[]; reason: string; equipment?: string[]; candidate?: LibEntry['candidate'] }): LibEntry {
  return ex({
    key: d.key,
    name: d.name,
    en: d.en,
    aliases: d.aliases,
    pose: PENDING_POSE,
    start: '',
    steps: [],
    equipment: d.equipment ?? [],
    pending: d.reason,
    candidate: d.candidate,
  });
}

